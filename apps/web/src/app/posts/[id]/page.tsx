import Link from "next/link";
import { notFound } from "next/navigation";
import { Suspense } from "react";
import { Badge, Notice, NotStated } from "@/components/ui";
import { ClosingText, StatusBadge, TypeBadge } from "@/components/opportunity-bits";
import { daysUntil, formatDate, formatDateTime } from "@/lib/format";
import { effectiveStatus, getOpportunity } from "@/lib/opportunities";
import { displayTitle } from "@/lib/text";
import { getCurrentUser } from "@/lib/session";
import { SaveButton } from "@/components/save-button";
import { getSaved, isSaved, markSeen } from "@/lib/saved";
import { Checklist } from "@/components/checklist";
import { CopyText } from "@/components/copy-text";
import { AiServiceError } from "@/lib/ai";
import { getChecklist, itemKey } from "@/lib/generated";
import { and, eq } from "drizzle-orm";
import { db, schema } from "@/db";
import { STATUS_LABEL } from "@/lib/applications";
import { SubmitButton } from "@/components/submit-button";
import { startApplication } from "@/app/applications/actions";

// The checklist may be generated by AI on first view.
export const maxDuration = 60;
import { trackFunnel } from "@/lib/funnel";

const FIELD_LABELS: Record<string, string> = {
  closingDate: "Closing date", minimumRequirements: "Requirements", applyRoute: "How to apply",
  location: "Location", salary: "Salary", status: "Status", documentsRequired: "Documents",
};

export default async function PostPage({ params }: { params: Promise<{ id: string }> }) {
  const { id } = await params;
  const data = await getOpportunity(id);
  if (!data) notFound();
  const { opp, dept, form, doc, versions } = data;
  const status = effectiveStatus(opp.status, opp.closingDate);
  const user = await getCurrentUser();
  const saved = user ? await isSaved(user.id, opp.id) : false;
  if (user && saved) await markSeen(user.id, opp.id, opp.currentVersion);
  await trackFunnel(opp.id, "viewed");
  const route = opp.applyRoute;
  const latestChange = versions.find((v) => v.v.version === opp.currentVersion && v.v.version > 1);
  const closed = status === "closed" || status === "withdrawn";
  const portal = route?.portal_url ? (route.portal_url.startsWith("http") ? route.portal_url : `https://${route.portal_url}`) : null;
  const left = daysUntil(opp.closingDate);
  const [myApp] = user
    ? await db.select().from(schema.applications).where(and(eq(schema.applications.userId, user.id), eq(schema.applications.opportunityId, opp.id)))
    : [];

  return (
    <div className="max-w-3xl space-y-8">
      {/* 1. What the job is, and how long you have */}
      <header>
        <div className="flex flex-wrap items-center gap-2 mb-3">
          <StatusBadge status={status} />
          <TypeBadge type={opp.type} />
        </div>
        <h1 className="text-3xl sm:text-4xl font-bold tracking-tight">{displayTitle(opp.postTitle)}</h1>
        <p className="mt-2 text-lg text-muted">
          {dept.name}{opp.location && ` · ${opp.location}`}{opp.salary && ` · ${opp.salary}`}
        </p>
        <p className={`mt-3 text-xl font-semibold ${left !== null && left >= 0 && left <= 3 ? "text-danger" : ""}`}>
          <ClosingText date={opp.closingDate} />
        </p>
      </header>

      {latestChange && (
        <Notice tone="warn">
          <strong>This post was {opp.status === "extended" ? "extended" : "amended"}</strong> on {formatDate(latestChange.v.approvedAt)}.
          Changed: {latestChange.v.changedFields.map((f) => FIELD_LABELS[f] ?? f).join(", ")}.{" "}
          <a href="#more" className="underline">See what changed</a>
        </Notice>
      )}
      {status === "withdrawn" && <Notice tone="danger">This post has been withdrawn. Do not apply.</Notice>}

      {/* 2. How to apply */}
      <section className="rounded-3xl bg-black text-white p-6 sm:p-8 space-y-5" aria-labelledby="apply">
        <div>
          <h2 id="apply" className="text-2xl font-bold !text-white">Apply for this job</h2>
          <p className="mt-1 text-white/70">
            Apply right here. Your application goes straight to {dept.name}, and you can follow its status under My applications.
          </p>
        </div>
        {closed ? (
          <p className="rounded-xl bg-white/10 px-4 py-3">This post is {status === "withdrawn" ? "withdrawn" : "closed"}. Applications are no longer accepted.</p>
        ) : (
          <div className="space-y-4">
            {myApp ? (
              <a href={`/applications/${myApp.id}`} className="flex items-center justify-between gap-3 rounded-2xl bg-white px-5 py-4 text-black font-semibold hover:bg-white/90" data-testid="my-application">
                <span>
                  {myApp.status === "draft" ? "Continue your application" : "View your application"}
                  <span className="block text-sm font-normal text-black/60">Status: {STATUS_LABEL[myApp.status]}</span>
                </span>
                <span aria-hidden className="text-2xl">→</span>
              </a>
            ) : user ? (
              <form action={startApplication}>
                <input type="hidden" name="opportunityId" value={opp.id} />
                <SubmitButton className="w-full !min-h-14 !rounded-2xl !bg-white !text-black text-lg hover:!bg-white/90" pendingText="Starting your application…">
                  Apply now →
                </SubmitButton>
              </form>
            ) : (
              <a href={`/sign-in?next=/posts/${opp.id}`} className="flex items-center justify-between rounded-2xl bg-white px-5 py-4 text-black text-lg font-semibold hover:bg-white/90">
                Sign in to apply <span aria-hidden className="text-2xl">→</span>
              </a>
            )}
            {opp.referenceNumber && (
              <p className="text-sm text-white/70">Reference number: <CopyText dark value={opp.referenceNumber} label="reference number" /></p>
            )}
            <details className="rounded-2xl border border-white/20 px-5 py-3 text-sm">
              <summary className="cursor-pointer text-white/80">Prefer to apply the department&apos;s way?</summary>
              <div className="mt-3 space-y-3">
            {portal && (
              <a href={portal} target="_blank" rel="noreferrer" className="flex items-center justify-between gap-3 rounded-2xl bg-white px-5 py-4 text-black font-semibold hover:bg-white/90">
                <span>Apply on the department&apos;s website<span className="block text-sm font-normal text-black/60 break-all">{route!.portal_url}</span></span>
                <span aria-hidden className="text-2xl">→</span>
              </a>
            )}
            {route?.email && (
              <div className="rounded-2xl bg-white/10 px-5 py-4">
                <p className="text-sm text-white/70">Email your application to</p>
                <CopyText dark value={route.email} label="email address" />
              </div>
            )}
            {route?.postal && (
              <div className="rounded-2xl bg-white/10 px-5 py-4">
                <p className="text-sm text-white/70">Or post it to</p>
                <p>{route.postal}</p>
              </div>
            )}
            {route?.hand_delivery && (
              <div className="rounded-2xl bg-white/10 px-5 py-4">
                <p className="text-sm text-white/70">Or hand it in at</p>
                <p>{route.hand_delivery}</p>
              </div>
            )}
            {!portal && !route?.email && !route?.postal && !route?.hand_delivery && (
              <p className="rounded-xl bg-white/10 px-4 py-3">The advert doesn&apos;t say how to apply. Contact the department{opp.contact?.phone ? ` on ${opp.contact.phone}` : ""}.</p>
            )}
              </div>
            </details>
          </div>
        )}
        <div className="flex flex-wrap gap-3 pt-1 [&_button]:!bg-white [&_button]:!text-black [&_a]:!bg-white [&_a]:!text-black">
          <div className="min-w-56"><SaveButton opportunityId={opp.id} saved={saved} signedIn={!!user} /></div>
        </div>
      </section>

      {/* 3. Get ready: the checklist, right here */}
      <section aria-labelledby="ready" className="space-y-3">
        <div className="flex flex-wrap items-end justify-between gap-2">
          <h2 id="ready" className="text-2xl font-bold">Get ready: what to send</h2>
          <Link href={`/posts/${opp.id}/explain`} className="text-sm font-semibold underline">Explain this job in simple words</Link>
        </div>
        <Suspense fallback={<div className="rounded-2xl border border-black/10 p-5 text-muted animate-pulse">Preparing your checklist…</div>}>
          <InlineChecklist oppId={opp.id} userId={user?.id ?? null} />
        </Suspense>
        {form?.officialUrl && (
          <p className="text-sm">Get the form: <a className="underline font-semibold" href={form.officialUrl} target="_blank" rel="noreferrer">{form.name} ({form.version})</a></p>
        )}
      </section>

      {/* 4. What you must have */}
      <section aria-labelledby="need" className="space-y-3">
        <h2 id="need" className="text-2xl font-bold">What you must have</h2>
        <List items={opp.minimumRequirements} />
        {(opp.contact?.name || opp.contact?.phone) && (
          <p className="text-sm text-muted">Questions about this job? Ask {[opp.contact?.name, opp.contact?.phone].filter(Boolean).join(" on ")}.</p>
        )}
      </section>

      {/* 5. Everything else, folded away */}
      <details id="more" open={!!latestChange} className="rounded-2xl border border-black/10 bg-white p-5 [&_summary]:cursor-pointer">
        <summary className="font-semibold">More about this advert</summary>
        <div className="mt-4 space-y-6">
          <div>
            <p className="text-sm text-muted">
              Source: {doc?.title ?? "Unknown"}{opp.sourceDate && `, published ${formatDate(opp.sourceDate)}`}.{" "}
              {doc?.sourceUrl && <a className="underline" href={doc.sourceUrl} target="_blank" rel="noreferrer">Official PDF</a>}
            </p>
            <details className="mt-2">
              <summary className="text-sm underline">Show the original wording</summary>
              <pre className="mt-2 whitespace-pre-wrap text-xs bg-background border border-border rounded-md p-3 max-h-[28rem] overflow-auto">{opp.sourceText}</pre>
            </details>
          </div>
          <div>
            <h3 className="font-semibold mb-2">Version history</h3>
            <ol className="space-y-3">
              {versions.map(({ v, approver, doc: vdoc }) => (
                <li key={v.id} className="text-sm border-l-2 border-border pl-3">
                  <div className="flex flex-wrap items-center gap-2">
                    <Badge tone={v.version === opp.currentVersion ? "brand" : "neutral"}>Version {v.version}</Badge>
                    <span className="text-muted">{formatDateTime(v.approvedAt)} · approved by {approver ?? "imported from the circular"}</span>
                  </div>
                  <p className="mt-1">{v.note}{vdoc && <span className="text-muted"> · {vdoc}</span>}</p>
                  {v.changedFields.length > 0 && <VersionDiff record={v.record} prev={versions.find((x) => x.v.version === v.version - 1)?.v.record} fields={v.changedFields} />}
                </li>
              ))}
            </ol>
          </div>
        </div>
      </details>

      <p className="text-sm text-muted">
        iGovPath helps you prepare. It does not decide who is shortlisted. <Link href="/search" className="underline">Back to search</Link>
      </p>
    </div>
  );
}

/** The application checklist, built from the approved advert (generated once per version, then cached). */
async function InlineChecklist({ oppId, userId }: { oppId: string; userId: string | null }) {
  const data = await getOpportunity(oppId);
  if (!data) return null;
  let items: { group: string; item: string; source: string }[] = [];
  try {
    items = await getChecklist(data.opp, data.dept.name);
  } catch (e) {
    if (e instanceof AiServiceError) {
      return <p className="rounded-2xl border border-black/10 p-5 text-muted">The checklist isn&apos;t available right now. Please try again in a moment.</p>;
    }
    throw e;
  }
  const saved = userId ? await getSaved(userId, oppId) : null;
  return (
    <div className="rounded-2xl border border-black/10 bg-white p-5">
      {!userId && <p className="mb-4 text-sm text-muted"><Link className="underline" href={`/sign-in?next=/posts/${oppId}`}>Sign in</Link> to tick items and keep your progress.</p>}
      <Checklist opportunityId={oppId} items={items.map((i) => ({ ...i, key: itemKey(i.group, i.item) }))} initial={saved?.checklistState ?? {}} signedIn={!!userId} showSource={false} />
    </div>
  );
}

function List({ items }: { items: string[] }) {
  if (!items?.length) return <NotStated />;
  return <ul className="list-disc pl-5 text-sm space-y-1">{items.map((x, i) => <li key={i}>{x}</li>)}</ul>;
}

function show(v: unknown): string {
  if (v == null || v === "") return "(not stated)";
  if (Array.isArray(v)) return v.join("; ");
  if (typeof v === "object") return Object.entries(v as Record<string, unknown>).filter(([, x]) => x).map(([k, x]) => `${k}: ${x}`).join("; ");
  return String(v);
}

function VersionDiff({ record, prev, fields }: { record: Record<string, unknown>; prev?: Record<string, unknown>; fields: string[] }) {
  return (
    <div className="mt-2 space-y-2">
      {fields.map((f) => (
        <div key={f} className="rounded-md border border-border overflow-hidden">
          <p className="text-xs font-medium px-2 py-1 bg-background">{FIELD_LABELS[f] ?? f}</p>
          <p className="px-2 py-1 text-xs bg-danger-soft"><span className="font-medium">Before:</span> {show(prev?.[f])}</p>
          <p className="px-2 py-1 text-xs bg-brand-soft"><span className="font-medium">Now:</span> {show(record[f])}</p>
        </div>
      ))}
    </div>
  );
}
