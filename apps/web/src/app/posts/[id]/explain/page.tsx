import Link from "next/link";
import { notFound } from "next/navigation";
import { Card, Notice, PageTitle } from "@/components/ui";
import { AiServiceError } from "@/lib/ai";
import { getExplanation, LANGUAGES, type ExplanationContent, type Language } from "@/lib/generated";
import { formatDate } from "@/lib/format";
import { getOpportunity } from "@/lib/opportunities";
import { displayTitle } from "@/lib/text";
import { trackFunnel } from "@/lib/funnel";

const SECTIONS: [string, string][] = [
  ["what_the_job_is", "What the job is"],
  ["what_you_must_have", "What you must have"],
  ["what_to_send", "What to send"],
  ["deadline_and_where", "Deadline and where to send it"],
  ["what_you_may_be_missing", "Anything you may be missing"],
];

export default async function ExplainPage({ params, searchParams }: { params: Promise<{ id: string }>; searchParams: Promise<{ lang?: string }> }) {
  const { id } = await params;
  const { lang } = await searchParams;
  const language: Language = (LANGUAGES as readonly string[]).includes(lang ?? "") ? (lang as Language) : "English";
  const data = await getOpportunity(id);
  if (!data) notFound();
  const { opp, dept } = data;
  let content: ExplanationContent | null = null;
  let error: string | null = null;
  try {
    content = await getExplanation(opp, dept.name, language);
    await trackFunnel(opp.id, "explained");
  } catch (e) {
    if (e instanceof AiServiceError) error = e.message;
    else throw e;
  }
  const route = opp.applyRoute;

  return (
    <div>
      <p className="text-sm mb-2"><Link className="text-brand underline" href={`/posts/${opp.id}`}>← {displayTitle(opp.postTitle)}</Link></p>
      <PageTitle sub={dept.name}>In plain language</PageTitle>
      <div className="flex gap-2 mb-4" role="tablist" aria-label="Language">
        {LANGUAGES.map((l) => (
          <Link key={l} role="tab" aria-selected={l === language} href={`/posts/${opp.id}/explain?lang=${l}`}
            className={`rounded-full px-3 py-1 text-sm border ${l === language ? "bg-brand text-brand-ink border-brand" : "border-border bg-surface"}`}>
            {l}
          </Link>
        ))}
      </div>
      {language !== "English" && (
        <div className="mb-4"><Notice tone="warn"><strong>Machine translation, needs native-speaker review.</strong> If anything is unclear, use the English version and the original advert.</Notice></div>
      )}
      {content && !content.fact_check_passed && (
        <div className="mb-4"><Notice tone="danger">Our automatic check found numbers that are not in the advert: {content.fact_problems.join("; ")}. Rely on the original wording.</Notice></div>
      )}
      {error && <Notice tone="danger">{error}</Notice>}
      <div className="grid gap-6 lg:grid-cols-2">
        <Card className="space-y-4" data-testid="explanation">
          <p className="text-xs uppercase tracking-wide text-muted">Explanation ({language})</p>
          {content && SECTIONS.map(([k, label]) => {
            const v = content!.explanation[k];
            return (
              <section key={k}>
                <h2 className="font-semibold text-sm">{label}</h2>
                {Array.isArray(v) ? (
                  <ul className="list-disc pl-5 text-sm space-y-1 mt-1">{v.map((x, i) => <li key={i}>{x}</li>)}</ul>
                ) : (
                  <p className="text-sm mt-1">{v || "—"}</p>
                )}
              </section>
            );
          })}
          {content && <p className="text-sm font-medium border-t border-border pt-3">{String(content.explanation.closing_line ?? "")}</p>}
          {content && <p className="text-xs text-muted">Generated by {content.model} from the approved record. Not a decision about you.</p>}
        </Card>
        <Card className="space-y-3">
          <p className="text-xs uppercase tracking-wide text-muted">Original wording</p>
          <dl className="text-sm space-y-2">
            <div><dt className="font-medium">Closing date</dt><dd>{opp.closingDate ? formatDate(opp.closingDate) : "Not stated in the advert"}</dd></div>
            <div><dt className="font-medium">Reference</dt><dd>{opp.referenceNumber ?? "Not stated in the advert"}</dd></div>
            <div><dt className="font-medium">Requirements</dt><dd><ul className="list-disc pl-5">{opp.minimumRequirements.map((r, i) => <li key={i}>{r}</li>)}</ul></dd></div>
            <div><dt className="font-medium">Documents</dt><dd><ul className="list-disc pl-5">{opp.documentsRequired.map((r, i) => <li key={i}>{r}</li>)}</ul></dd></div>
            <div><dt className="font-medium">Apply</dt><dd>{[route?.portal_url, route?.email, route?.postal, route?.hand_delivery].filter(Boolean).join(" · ") || "Not stated in the advert"}</dd></div>
          </dl>
          <details>
            <summary className="cursor-pointer text-sm text-brand">Full advert text</summary>
            <pre className="mt-2 whitespace-pre-wrap text-xs max-h-96 overflow-auto">{opp.sourceText}</pre>
          </details>
        </Card>
      </div>
    </div>
  );
}
